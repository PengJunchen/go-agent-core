// Package production 定义 go-agent-core 的生产化组件接口。
//
// 本包仅包含接口定义和配置类型，不含具体实现。
// 遵循接口先行原则（D3），确保组件可插拔、可替换。
//
// 六大横切能力：
//
// - CircuitBreaker：熔断器，防止级联故障。当错误率超过阈值时自动断开，
// 一段时间后进入半开状态探测恢复，恢复后自动闭合。
//
// - LoopDetector：循环检测，防止无限工具调用循环。通过分析连续调用模式，
// 在检测到重复调用时发出警告或阻止执行。
//
// - IdempotencyKey：幂等键，确保操作可安全重试。通过记录已完成操作的结果，
// 在重试时直接返回缓存结果，避免重复执行副作用操作。
//
// - SecurityGuard：安全守卫，校验操作是否符合安全策略。可对工具调用和用户输入
// 进行校验，支持允许、阻止、要求审批和消毒四种决策。
//
// - AuditLogger：审计日志，记录合规相关事件。记录工具调用、审批决策和数据访问，
// 支持按条件查询历史记录。
//
// - TelemetryCollector：遥测采集，收集指标和链路追踪。支持记录数值指标、
// 创建追踪 Span 和记录错误事件。
//
// 所有接口通过依赖注入装配，框架不硬编码具体实现。
package production
